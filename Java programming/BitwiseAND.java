public class BitwiseAND
{
    public static void main(String args[])
    {
        int num1 = 34;
        int num2 = 23;

        int result = num1 & num2;

        System.out.println("First Number : " + num1);
        System.out.println("Second Number : " + num2);
        System.out.println("Bitwise AND : " + result);
    }
}