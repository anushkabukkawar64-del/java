public class Main4 {

    static int multiply(int a, int b) {
        return a * b;
    }

    static double multiply(double a, double b) {
        return a * b;
    }

    public static void main(String[] args) {

        System.out.println(multiply(5, 10));

        System.out.println(multiply(5.5, 2.5));
    }
}